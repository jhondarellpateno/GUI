    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        String oid = jTextField2.getText();
        String newStatus = jComboBox1.getSelectedItem().toString();

        if (oid.isEmpty()) {
            JOptionPane.showMessageDialog(null, "Please select an order from the table first.");
            return;
        }

        int confirm = JOptionPane.showConfirmDialog(null,
                "Change Order #" + oid + " status to " + newStatus + "?",
                "Confirm Update", JOptionPane.YES_NO_OPTION);

        if (confirm == JOptionPane.YES_OPTION) {
            config conf = new config();

            String sql = "UPDATE tbl_order SET o_status = ? WHERE o_id = ?";
            conf.updateRecord(sql, newStatus, oid);

            displaySupplierOrders();

            jTextField2.setText("");

            JOptionPane.showMessageDialog(null, "Order #" + oid + " is now " + newStatus + "!");
        }
    }//GEN-LAST:event_jButton1ActionPerformed

