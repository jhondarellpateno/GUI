    public void displaySupplierOrders() {
        config conf = new config();
        DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
        model.setRowCount(0);

        try {
            int loggedInID = UserSession.getInstance().getU_id();

            String sql = "SELECT o_id, i_id, o_name, o_category, o_size, o_color, o_amountpay, o_status " + "FROM tbl_order WHERE u_id = '" + loggedInID + "'";

            java.util.List<java.util.Map<String, Object>> records = conf.fetchRecords(sql);

            for (java.util.Map<String, Object> row : records) {
                model.addRow(new Object[]{
                    row.get("o_id"),
                    row.get("i_id"),
                    row.get("o_name"),
                    row.get("o_category"),
                    row.get("o_size"),
                    row.get("o_color"),
                    row.get("o_amountpay"),
                    row.get("o_status")
                });
            }
        } catch (Exception e) {
            System.out.println("Error loading supplier orders: " + e.getMessage());
        }
    }

